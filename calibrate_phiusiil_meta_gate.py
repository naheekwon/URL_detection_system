import os
import re
import urllib.parse

import joblib
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

import app as inference_app


SEED = 42

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
PARENT_DIR = os.path.dirname(PROJECT_DIR)

PHIUSIIL_CANDIDATE_PATHS = [
    os.path.join(PROJECT_DIR, "PhiUSIIL_Phishing_URL_Dataset.csv"),
    os.path.join(PARENT_DIR, "PhiUSIIL_Phishing_URL_Dataset.csv"),
]
MAIN_DATA_PATH = os.path.join(PROJECT_DIR, "malicious_phish.csv")

ARTIFACT_DIR = os.path.join(PROJECT_DIR, "artifacts_phiusiil_meta_gate")
RESULT_DIR = os.path.join(PROJECT_DIR, "results_phiusiil_meta_gate")

URL_COL = "url"
LABEL_COL = "type"
BENIGN_LABEL = "benign"
PHISHING_LABEL = "phishing"

# Full PhiUSIIL is large. These caps keep the experiment practical while still
# giving enough short legitimate URLs to calibrate the service decision layer.
CALIBRATION_RATIO = 0.70
MAX_CALIBRATION_EACH = 30000
MAX_EXTERNAL_TEST_EACH = 15000
INFERENCE_BATCH_SIZE = 512

# Higher penalty means "avoid false phishing alarms on benign URLs".
META_FP_PENALTY = 0.85
META_CLASS_WEIGHT = {0: 1.6, 1: 1.0}

THRESHOLD_MIN = 0.05
THRESHOLD_MAX = 0.95
THRESHOLD_STEP = 0.01

os.makedirs(ARTIFACT_DIR, exist_ok=True)
os.makedirs(RESULT_DIR, exist_ok=True)


def resolve_phiusiil_path():
    for path in PHIUSIIL_CANDIDATE_PATHS:
        if os.path.exists(path):
            return path

    raise FileNotFoundError(
        "PhiUSIIL_Phishing_URL_Dataset.csv not found. Checked:\n"
        + "\n".join(PHIUSIIL_CANDIDATE_PATHS)
    )


def clean_url_text(url):
    if url is None:
        url = ""

    url = str(url).strip().lower()

    try:
        url = urllib.parse.unquote(url, errors="ignore")
    except Exception:
        pass

    url = url.replace("[", "").replace("]", "")
    url = re.sub(r"[\x00-\x1f\x7f]", "", url)

    return url


def safe_parse_url(url):
    cleaned = clean_url_text(url)

    try:
        parse_target = cleaned
        if not re.match(r"^[a-zA-Z][a-zA-Z0-9+\-.]*://", parse_target):
            parse_target = "http://" + parse_target
        return urllib.parse.urlparse(parse_target)
    except Exception:
        return urllib.parse.urlparse("http://invalid.local/")


def normalize_phi_label(label):
    """
    PhiUSIIL official mapping:
    1 -> legitimate URL -> benign
    0 -> phishing URL
    """
    s = str(label).strip().lower()

    if s in {"1", "1.0", "legitimate", "legit", "benign", "safe", "normal"}:
        return BENIGN_LABEL

    if s in {"0", "0.0", "phishing", "phish", "malicious"}:
        return PHISHING_LABEL

    return None


def load_phiusiil_binary_dataset():
    path = resolve_phiusiil_path()
    df = pd.read_csv(path, usecols=["URL", "label"])
    df = df.rename(columns={"URL": URL_COL, "label": LABEL_COL})
    df[URL_COL] = df[URL_COL].astype(str).map(clean_url_text)
    df[LABEL_COL] = df[LABEL_COL].map(normalize_phi_label)
    df = df.dropna(subset=[URL_COL, LABEL_COL])
    df = df[df[LABEL_COL].isin([BENIGN_LABEL, PHISHING_LABEL])].copy()
    df = df.drop_duplicates(subset=[URL_COL]).reset_index(drop=True)

    if os.path.exists(MAIN_DATA_PATH):
        main_urls = pd.read_csv(MAIN_DATA_PATH, usecols=[URL_COL])[URL_COL]
        main_urls = set(main_urls.astype(str).map(clean_url_text))
        before = len(df)
        df = df[~df[URL_COL].isin(main_urls)].copy().reset_index(drop=True)
        print(f"Removed URL overlap with malicious_phish.csv: {before - len(df)}")

    print("\n[PhiUSIIL external dataset]")
    print("Path:", path)
    print("Rows:", len(df))
    print(df[LABEL_COL].value_counts())

    return df


def balanced_sample(df, max_each, random_state):
    parts = []

    for label in [BENIGN_LABEL, PHISHING_LABEL]:
        group = df[df[LABEL_COL] == label]
        n = min(len(group), max_each)
        parts.append(group.sample(n=n, random_state=random_state))

    sampled = pd.concat(parts, axis=0)
    sampled = sampled.sample(frac=1.0, random_state=random_state).reset_index(drop=True)

    return sampled


def split_external_dataset(df):
    calibration_df, test_df = train_test_split(
        df,
        train_size=CALIBRATION_RATIO,
        random_state=SEED,
        stratify=df[LABEL_COL],
    )

    calibration_df = balanced_sample(
        calibration_df,
        max_each=MAX_CALIBRATION_EACH,
        random_state=SEED + 1,
    )
    test_df = balanced_sample(
        test_df,
        max_each=MAX_EXTERNAL_TEST_EACH,
        random_state=SEED + 2,
    )

    print("\n[Calibration split]")
    print(calibration_df[LABEL_COL].value_counts())
    print("\n[External test split]")
    print(test_df[LABEL_COL].value_counts())

    return calibration_df, test_df


def url_policy_features(urls):
    rows = []

    for url in urls:
        u = clean_url_text(url)
        parsed = safe_parse_url(u)
        host = inference_app.get_normalized_host(u)
        path = parsed.path or ""
        query = parsed.query or ""
        domain_parts = [p for p in host.split(".") if p]

        known_safe_domain = inference_app.matched_known_safe_domain(host)
        known_safe_risky = inference_app.has_strong_known_safe_risk_signal(u)

        rows.append([
            float(len(u)),
            float(len(host)),
            float(len(path)),
            float(len(query)),
            float(u.count(".")),
            float(u.count("-")),
            float(u.count("_")),
            float(u.count("@")),
            float(u.count("%")),
            float(u.count("=")),
            float(u.count("&")),
            float(len(domain_parts)),
            1.0 if query else 0.0,
            1.0 if path and path != "/" else 0.0,
            1.0 if (not path or path == "/") and not query else 0.0,
            1.0 if len(u) <= 35 else 0.0,
            1.0 if len(u) <= 50 else 0.0,
            1.0 if known_safe_domain is not None else 0.0,
            1.0 if known_safe_risky else 0.0,
            1.0 if host.endswith(".ac.kr") or host.endswith(".edu") else 0.0,
            1.0 if host.endswith(".go.kr") or host.endswith(".gov") else 0.0,
            1.0 if host.endswith(".co.kr") else 0.0,
        ])

    return np.array(rows, dtype=np.float32)


def iter_batches(items, batch_size):
    for start in range(0, len(items), batch_size):
        yield start, items[start:start + batch_size]


def predict_transformer_probs_batched(urls, batch_size=INFERENCE_BATCH_SIZE):
    chunks = []

    for _, batch_urls in iter_batches(urls, batch_size):
        chunks.append(inference_app.predict_transformer_phishing_probs(batch_urls))

    if not chunks:
        return np.array([], dtype=np.float32)

    return np.concatenate(chunks).astype(np.float32)


def extract_meta_features(urls):
    benign_id = inference_app.benign_id
    phishing_id = inference_app.phishing_id

    rows = []
    base_proba_chunks = []
    base_pred_chunks = []
    transformer_chunks = []

    for batch_idx, batch_urls in iter_batches(urls, INFERENCE_BATCH_SIZE):
        print(f"  feature batch {batch_idx // INFERENCE_BATCH_SIZE + 1} / {int(np.ceil(len(urls) / INFERENCE_BATCH_SIZE))}")

        x_base = inference_app.build_features(batch_urls)
        base_proba = inference_app.base_model.predict_proba(x_base)
        base_pred = np.argmax(base_proba, axis=1)
        transformer_probs = predict_transformer_probs_batched(batch_urls)

        sorted_probs = np.sort(base_proba, axis=1)
        top_margin = sorted_probs[:, -1] - sorted_probs[:, -2]
        policy = url_policy_features(batch_urls)

        base_proba_chunks.append(base_proba)
        base_pred_chunks.append(base_pred)
        transformer_chunks.append(transformer_probs)

        for i in range(len(batch_urls)):
            base_benign = float(base_proba[i][benign_id])
            base_phishing = float(base_proba[i][phishing_id])
            transformer_phishing = float(transformer_probs[i])

            row = [
                base_benign,
                base_phishing,
                base_phishing - base_benign,
                abs(base_phishing - base_benign),
                float(np.max(base_proba[i])),
                float(top_margin[i]),
                1.0 if base_pred[i] == benign_id else 0.0,
                1.0 if base_pred[i] == phishing_id else 0.0,
                transformer_phishing,
                transformer_phishing - base_phishing,
                abs(transformer_phishing - base_phishing),
            ]
            row.extend(policy[i].tolist())
            rows.append(row)

    return (
        np.array(rows, dtype=np.float32),
        np.vstack(base_proba_chunks),
        np.concatenate(base_pred_chunks),
        np.concatenate(transformer_chunks),
    )


