def current_app_predictions(urls):
    preds = []

    for _, batch_urls in iter_batches(urls, INFERENCE_BATCH_SIZE):
        results, _ = inference_app.hybrid_predict(batch_urls)
        preds.extend([
            1 if row["prediction"] == PHISHING_LABEL else 0
            for row in results
        ])

    return np.array(preds, dtype=int)


def find_best_threshold(y_true, scores):
    rows = []
    best = None

    for threshold in np.arange(THRESHOLD_MIN, THRESHOLD_MAX + 1e-9, THRESHOLD_STEP):
        y_pred = (scores >= threshold).astype(int)
        precision = precision_score(y_true, y_pred, zero_division=0)
        recall = recall_score(y_true, y_pred, zero_division=0)
        f1 = f1_score(y_true, y_pred, zero_division=0)

        benign_fp = int(np.sum((y_true == 0) & (y_pred == 1)))
        benign_total = int(np.sum(y_true == 0))
        benign_fp_rate = benign_fp / max(benign_total, 1)

        objective = f1 - META_FP_PENALTY * benign_fp_rate
        row = {
            "threshold": float(threshold),
            "precision": float(precision),
            "recall": float(recall),
            "f1": float(f1),
            "benign_fp": benign_fp,
            "benign_total": benign_total,
            "benign_fp_rate": float(benign_fp_rate),
            "objective": float(objective),
        }
        rows.append(row)

        if best is None or objective > best["objective"]:
            best = row

    return best, pd.DataFrame(rows)


def evaluate_binary(y_true, y_pred, title):
    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])

    return {
        "title": title,
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "phishing_precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "phishing_recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "phishing_f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "benign_recall": float(recall_score(y_true, y_pred, pos_label=0, zero_division=0)),
        "benign_to_phishing": int(cm[0][1]),
        "phishing_to_benign": int(cm[1][0]),
        "confusion_matrix": cm.tolist(),
        "classification_report": classification_report(
            y_true,
            y_pred,
            target_names=[BENIGN_LABEL, PHISHING_LABEL],
            output_dict=True,
            zero_division=0,
        ),
    }


def print_report(report):
    print(f"\n[{report['title']}]")
    print("Accuracy:", round(report["accuracy"], 4))
    print("Benign recall:", round(report["benign_recall"], 4))
    print(
        "Phishing P/R/F1:",
        round(report["phishing_precision"], 4),
        round(report["phishing_recall"], 4),
        round(report["phishing_f1"], 4),
    )
    print("Benign -> Phishing:", report["benign_to_phishing"])
    print("Phishing -> Benign:", report["phishing_to_benign"])
    print("Confusion matrix [0=benign, 1=phishing]:")
    print(np.array(report["confusion_matrix"]))


def debug_urls(meta_gate, scaler, threshold):
    urls = [
        "https://www.airbnb.co.kr/",
        "https://www.dankook.ac.kr/",
        "https://www.tistory.com/",
        "https://notice.tistory.com/",
        "https://www.google.com/",
        "https://www.naver.com/",
        "https://www.11st.co.kr/main",
        "https://google.com.verify-login-security.xyz",
    ]

    x_raw, _, _, transformer_probs = extract_meta_features(urls)
    x = scaler.transform(x_raw)
    scores = meta_gate.predict_proba(x)[:, 1]
    current_pred = current_app_predictions(urls)
    meta_pred = (scores >= threshold).astype(int)

    rows = []
    for i, url in enumerate(urls):
        rows.append({
            "url": url,
            "current_app_prediction": PHISHING_LABEL if current_pred[i] else BENIGN_LABEL,
            "meta_gate_prediction": PHISHING_LABEL if meta_pred[i] else BENIGN_LABEL,
            "meta_phishing_score": float(scores[i]),
            "threshold": float(threshold),
            "transformer_phishing_probability": float(transformer_probs[i]),
        })

    return rows


def main():
    phi_df = load_phiusiil_binary_dataset()
    calibration_df, test_df = split_external_dataset(phi_df)

    calibration_urls = calibration_df[URL_COL].tolist()
    test_urls = test_df[URL_COL].tolist()
    y_cal = (calibration_df[LABEL_COL].values == PHISHING_LABEL).astype(int)
    y_test = (test_df[LABEL_COL].values == PHISHING_LABEL).astype(int)

    print("\nExtracting calibration features with fixed existing model...")
    x_cal_raw, _, _, _ = extract_meta_features(calibration_urls)

    print("Extracting external test features with fixed existing model...")
    x_test_raw, _, _, test_transformer_probs = extract_meta_features(test_urls)

    meta_scaler = StandardScaler()
    x_cal = meta_scaler.fit_transform(x_cal_raw)
    x_test = meta_scaler.transform(x_test_raw)

    meta_gate = LogisticRegression(
        class_weight=META_CLASS_WEIGHT,
        max_iter=1000,
        random_state=SEED,
        solver="lbfgs",
    )
    meta_gate.fit(x_cal, y_cal)

    cal_scores = meta_gate.predict_proba(x_cal)[:, 1]
    best_threshold, threshold_df = find_best_threshold(y_cal, cal_scores)

    threshold_path = os.path.join(RESULT_DIR, "threshold_search_results.csv")
    threshold_df.to_csv(threshold_path, index=False)

    test_scores = meta_gate.predict_proba(x_test)[:, 1]
    y_meta = (test_scores >= best_threshold["threshold"]).astype(int)
    y_current = current_app_predictions(test_urls)

    current_report = evaluate_binary(y_test, y_current, "current_app_hybrid_on_phiusiil_test")
    meta_report = evaluate_binary(y_test, y_meta, "meta_gate_on_phiusiil_test")
    debug_rows = debug_urls(meta_gate, meta_scaler, best_threshold["threshold"])

    predictions_df = pd.DataFrame({
        "url": test_urls,
        "true_label": test_df[LABEL_COL].tolist(),
        "current_app_pred": [PHISHING_LABEL if v else BENIGN_LABEL for v in y_current],
        "meta_gate_pred": [PHISHING_LABEL if v else BENIGN_LABEL for v in y_meta],
        "meta_phishing_score": test_scores,
        "transformer_phishing_probability": test_transformer_probs,
    })
    predictions_path = os.path.join(RESULT_DIR, "external_test_predictions.csv")
    predictions_df.to_csv(predictions_path, index=False)

    summary = {
        "experiment": "phiusiil_posthoc_meta_gate_calibration",
        "data_policy": {
            "kaggle_malicious_phish_usage": (
                "Only through pre-existing artifacts_transformer. "
                "PhiUSIIL is not mixed into Kaggle 4-class training."
            ),
            "phiusiil_usage": (
                "Calibration split trains threshold/meta-gate. "
                "External test split is held out and used only for final evaluation."
            ),
            "overlap_removed_with_malicious_phish": True,
        },
        "sizes": {
            "calibration": int(len(calibration_df)),
            "external_test": int(len(test_df)),
        },
        "meta_gate": {
            "class_weight": META_CLASS_WEIGHT,
            "fp_penalty": META_FP_PENALTY,
            "selected_threshold": best_threshold,
            "feature_names": META_FEATURE_NAMES,
        },
        "current_app_hybrid": current_report,
        "meta_gate_result": meta_report,
        "manual_debug": debug_rows,
    }

    summary_path = os.path.join(RESULT_DIR, "summary.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)

    joblib.dump(meta_gate, os.path.join(ARTIFACT_DIR, "meta_gate.joblib"))
    joblib.dump(meta_scaler, os.path.join(ARTIFACT_DIR, "meta_gate_scaler.joblib"))

    config = {
        "model_family": "posthoc_phiusiil_benign_phishing_meta_gate",
        "source_artifact_dir": inference_app.ARTIFACT_DIR,
        "source_app": "app.py",
        "threshold": best_threshold["threshold"],
        "feature_names": META_FEATURE_NAMES,
        "feature_count": len(META_FEATURE_NAMES),
        "label_mapping": {
            "0": BENIGN_LABEL,
            "1": PHISHING_LABEL,
        },
        "phiusiil_label_mapping": {
            "1": "benign",
            "0": "phishing",
        },
        "artifact_files": {
            "meta_gate": "meta_gate.joblib",
            "meta_gate_scaler": "meta_gate_scaler.joblib",
            "config": "config.json",
        },
        "integration_note": (
            "To integrate with app.py later, load meta_gate/meta_gate_scaler after "
            "the existing base/Transformer prediction, recreate the same meta features, "
            "and apply score >= threshold only for benign/phishing candidate decisions."
        ),
    }
    config_path = os.path.join(ARTIFACT_DIR, "config.json")
    with open(config_path, "w", encoding="utf-8") as f:
        json.dump(config, f, ensure_ascii=False, indent=2)

    print("\n================ Threshold Selection ================")
    print("Selected threshold:", round(best_threshold["threshold"], 4))
    print("Calibration F1:", round(best_threshold["f1"], 4))
    print("Calibration benign FP rate:", round(best_threshold["benign_fp_rate"], 4))

    print("\n================ External Test Comparison ================")
    print_report(current_report)
    print_report(meta_report)

    print("\n================ Manual Debug URLs ================")
    for row in debug_rows:
        print(
            row["url"],
            "| current:",
            row["current_app_prediction"],
            "| meta:",
            row["meta_gate_prediction"],
            "| score:",
            round(row["meta_phishing_score"], 4),
        )

    print("\nSaved:")
    print(" -", threshold_path)
    print(" -", predictions_path)
    print(" -", summary_path)
    print(" -", os.path.join(ARTIFACT_DIR, "meta_gate.joblib"))
    print(" -", os.path.join(ARTIFACT_DIR, "meta_gate_scaler.joblib"))
    print(" -", config_path)


if __name__ == "__main__":
    main()
