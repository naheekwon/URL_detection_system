"""
LinkWatcher PhiUSIIL meta-gate calibration experiment.

This script is intentionally test/calibration-only:
- It does NOT retrain transformer_final.py.
- It does NOT modify app.py.
- It does NOT mix PhiUSIIL into the Kaggle 4-class training set.
- It loads the existing artifacts_transformer through app.py and keeps them fixed.

Purpose:
- Use PhiUSIIL only as an external benign/phishing calibration/test dataset.
- Learn a small post-hoc meta-gate that reduces benign -> phishing false positives,
  especially for short or unfamiliar legitimate URLs.
- Save artifacts that can be wired into app.py later if the experiment is good.

Required input:
- artifacts_transformer/ generated by transformer_final.py
- PhiUSIIL_Phishing_URL_Dataset.csv with columns URL,label
  Official mapping: label 1 = legitimate/benign, label 0 = phishing

Outputs:
- artifacts_phiusiil_meta_gate/
  - meta_gate.joblib
  - meta_gate_scaler.joblib
  - config.json
- results_phiusiil_meta_gate/
  - threshold_search_results.csv
  - external_test_predictions.csv
  - summary.json
"""

